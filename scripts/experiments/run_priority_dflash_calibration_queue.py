#!/usr/bin/env python3
"""Resume-safe production-SGLang calibration gate for the priority P5 lane.

Static is measured once on Math500.  Each TTS mode/learning-rate candidate is
kept in its own artifact root because learning rate is an execution overlay,
not a RunUnit identity field.  The selected candidate is then frozen for the
held-out LiveCodeBench 512--40K manifest.  A hash-bound downstream-ready
receipt is emitted only when the held-out acceptance and safety gates pass.
"""

from __future__ import annotations

import argparse
import fcntl
import hashlib
import json
import math
import os
import re
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Iterable, Sequence


GIB = 1 << 30
SAFE_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
NONFINITE = re.compile(r"(?:non.?finite|\bnan\b|\binf(?:inity)?\b)", re.I)


class QueueError(RuntimeError):
    pass


class ScientificBlock(QueueError):
    pass


@dataclass(frozen=True)
class Candidate:
    candidate_id: str
    weight_update_mode: str
    learning_rate: float

    def to_dict(self) -> dict[str, Any]:
        return {
            "candidate_id": self.candidate_id,
            "weight_update_mode": self.weight_update_mode,
            "learning_rate": self.learning_rate,
        }


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def source_tree_fingerprint(root: Path) -> dict[str, Any]:
    """Content-bind one Python source tree without retaining every file row.

    Calibration receipts are resumable across process and machine restarts,
    but never across an implementation change.  The model/environment lock
    does not cover a dirty workspace, so bind both the LightCone and SGLang
    execution trees explicitly.  Cache files and generated bytecode are not
    source and therefore cannot perturb the contract.
    """

    root = root.resolve()
    records = []
    total_bytes = 0
    for path in sorted(root.rglob("*.py")):
        relative = path.relative_to(root)
        if "__pycache__" in relative.parts or not path.is_file():
            continue
        size = path.stat().st_size
        total_bytes += size
        records.append(
            {
                "path": relative.as_posix(),
                "bytes": size,
                "sha256": sha256_file(path),
            }
        )
    if not records:
        raise QueueError(f"runtime source tree has no Python files: {root}")
    body = json.dumps(records, separators=(",", ":"), sort_keys=True).encode(
        "utf-8"
    )
    return {
        "root": str(root),
        "file_count": len(records),
        "total_bytes": total_bytes,
        "merkle_sha256": hashlib.sha256(body).hexdigest(),
    }


def _atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(text, encoding="utf-8")
    os.replace(temporary, path)


def _json_safe(value):
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    return value


def write_attested_json(
    path: Path,
    payload: dict[str, Any],
    *,
    evidence: Iterable[Path] = (),
) -> dict[str, Any]:
    rows = []
    for item in dict.fromkeys(Path(value).resolve() for value in evidence):
        if not item.is_file():
            raise QueueError(f"attestation evidence is missing: {item}")
        rows.append({"path": str(item), "sha256": sha256_file(item)})
    body = _json_safe({**payload, "evidence": rows})
    text = json.dumps(body, indent=2, sort_keys=True, allow_nan=False) + "\n"
    _atomic_text(path, text)
    _atomic_text(Path(str(path) + ".sha256"), sha256_file(path) + "\n")
    return body


def load_attested_json(path: Path) -> dict[str, Any]:
    sidecar = Path(str(path) + ".sha256")
    if not path.is_file() or not sidecar.is_file():
        raise QueueError(f"attested receipt is incomplete: {path}")
    if sidecar.read_text(encoding="utf-8").strip() != sha256_file(path):
        raise QueueError(f"receipt hash drift: {path}")
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise QueueError(f"receipt is not an object: {path}")
    for row in payload.get("evidence", []):
        evidence_path = Path(row["path"])
        if not evidence_path.is_file() or sha256_file(evidence_path) != row.get(
            "sha256"
        ):
            raise QueueError(f"receipt evidence drift: {evidence_path}")
    return payload


def _verify_sidecar(path: Path) -> None:
    sidecar = Path(str(path) + ".sha256")
    if not sidecar.is_file():
        raise QueueError(f"missing SHA-256 sidecar: {sidecar}")
    if sidecar.read_text(encoding="utf-8").strip() != sha256_file(path):
        raise QueueError(f"SHA-256 sidecar mismatch: {path}")


def load_candidate_spec(path: Path) -> tuple[list[Candidate], dict, dict]:
    _verify_sidecar(path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("schema_version") != 1:
        raise QueueError("candidate spec schema_version must be 1")
    raw = payload.get("candidates")
    if not isinstance(raw, list) or not raw:
        raise QueueError("candidate spec requires a non-empty candidates list")
    candidates = []
    for row in raw:
        candidate_id = str(row.get("candidate_id", ""))
        mode = str(row.get("weight_update_mode", ""))
        lr = row.get("learning_rate")
        if not SAFE_ID.fullmatch(candidate_id):
            raise QueueError(f"unsafe candidate_id: {candidate_id!r}")
        if mode not in {"residual", "lora", "full"}:
            raise QueueError(f"unsupported candidate mode: {mode!r}")
        if isinstance(lr, bool) or not isinstance(lr, (int, float)):
            raise QueueError(f"candidate {candidate_id} has invalid learning rate")
        lr = float(lr)
        if not math.isfinite(lr) or lr <= 0:
            raise QueueError(f"candidate {candidate_id} has invalid learning rate")
        candidates.append(Candidate(candidate_id, mode, lr))
    ids = [candidate.candidate_id for candidate in candidates]
    if len(set(ids)) != len(ids):
        raise QueueError("candidate IDs must be unique")
    calibration_gate = payload.get("calibration_gate")
    evaluation_gate = payload.get("evaluation_gate")
    if not isinstance(calibration_gate, dict) or not isinstance(
        evaluation_gate, dict
    ):
        raise QueueError("candidate spec requires both gate objects")
    numeric_fields = {
        "calibration_gate": (
            calibration_gate,
            {
                "max_context_regression",
                "max_hbm_delta_gib",
                "max_peak_hbm_gib",
                "min_lcag",
                "min_positive_contexts",
                "min_throughput_ratio",
            },
        ),
        "evaluation_gate": (
            evaluation_gate,
            {
                "max_context_regression",
                "max_hbm_delta_gib",
                "max_peak_hbm_gib",
                "min_lcag",
                "min_lcag_ci_low",
                "min_positive_contexts_per_concurrency",
                "min_throughput_ratio",
            },
        ),
    }
    for label, (gate, fields) in numeric_fields.items():
        missing = sorted(fields - set(gate))
        if missing:
            raise QueueError(f"{label} lacks fields: {missing}")
        for field in fields:
            value = gate[field]
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise QueueError(f"{label}.{field} must be numeric")
            if not math.isfinite(float(value)):
                raise QueueError(f"{label}.{field} must be finite")
            if float(value) < 0:
                raise QueueError(f"{label}.{field} must be nonnegative")
    if calibration_gate["min_positive_contexts"] < 1:
        raise QueueError("calibration min_positive_contexts must be positive")
    if evaluation_gate["min_positive_contexts_per_concurrency"] < 1:
        raise QueueError(
            "evaluation min_positive_contexts_per_concurrency must be positive"
        )
    if evaluation_gate.get("require_all_contexts_nonnegative") is not True:
        raise QueueError(
            "evaluation must require every context point estimate to be nonnegative"
        )
    expected_contexts = evaluation_gate.get("expected_contexts")
    expected_concurrencies = evaluation_gate.get("expected_concurrencies")
    allowed_contexts = (
        [512, 4096, 16384, 40000],
        [10000, 20000, 30000, 40000],
    )
    if expected_contexts not in allowed_contexts:
        raise QueueError(
            "evaluation contexts must be exact-prefix 512/4K/16K/40K or "
            "continuous generated windows ending at 10K/20K/30K/40K"
        )
    if not isinstance(expected_concurrencies, list) or not expected_concurrencies:
        raise QueueError("evaluation requires at least one concurrency")
    if any(
        isinstance(value, bool) or not isinstance(value, int) or value <= 0
        for value in expected_concurrencies
    ):
        raise QueueError("evaluation concurrencies must be positive integers")
    return candidates, calibration_gate, evaluation_gate


def _manifest_contract(calibration: Path, evaluation: Path) -> None:
    from lightcone_spec.orchestration.manifest import ExperimentManifest

    calibration_manifest = ExperimentManifest.load(calibration)
    evaluation_manifest = ExperimentManifest.load(evaluation)
    calibration_methods = {unit.method for unit in calibration_manifest.units}
    if calibration_methods != {"static", "tts"}:
        raise QueueError("calibration manifest must contain only Static and TTS")
    calibration_datasets = {unit.dataset for unit in calibration_manifest.units}
    evaluation_datasets = {unit.dataset for unit in evaluation_manifest.units}
    if len(calibration_datasets) != 1 or len(evaluation_datasets) != 1:
        raise QueueError("priority manifests must each use exactly one dataset")
    if calibration_datasets & evaluation_datasets:
        raise QueueError("calibration and held-out datasets must be disjoint")
    if calibration_datasets != {"math500"}:
        raise QueueError("priority calibration dataset must be Math500")
    if evaluation_datasets != {"livecodebench"}:
        raise QueueError("priority held-out dataset must be LiveCodeBench")
    if not {"static", "tts"}.issubset(
        {unit.method for unit in evaluation_manifest.units}
    ):
        raise QueueError("held-out manifest lacks Static or TTS")
    for unit in (*calibration_manifest.units, *evaluation_manifest.units):
        if unit.model_pair != "qwen3_4b_dflash16":
            raise QueueError("priority calibration is pinned to Qwen3-4B DFlash16")


def _state(root: Path, step: str, status: str, detail: str = "") -> None:
    root.mkdir(parents=True, exist_ok=True)
    row = {
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "step": step,
        "status": status,
        "detail": detail,
    }
    with (root / "queue-state.jsonl").open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, sort_keys=True) + "\n")
        handle.flush()
        os.fsync(handle.fileno())


def _command_text(command: Sequence[str]) -> str:
    import shlex

    return shlex.join(str(value) for value in command)


def _run_commands(
    root: Path,
    step: str,
    commands: Sequence[Sequence[str]],
    receipt: Path,
    evidence: Callable[[], Iterable[Path]],
) -> bool:
    if receipt.is_file() or Path(str(receipt) + ".sha256").is_file():
        load_attested_json(receipt)
        _state(root, step, "skipped", "hash-closed receipt")
        return True
    log = root / "logs" / f"{step}.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    _state(root, step, "started")
    started = time.time()
    headline_env = os.environ.copy()
    # The historical q00 reference harness opts into deterministic CUDA.  A
    # production SGLang calibration must not inherit knobs that serialize
    # launches or constrain GEMM selection when this queue is started by the
    # same parent process.
    headline_env.pop("CUBLAS_WORKSPACE_CONFIG", None)
    headline_env.pop("CUDA_LAUNCH_BLOCKING", None)
    with log.open("a", encoding="utf-8") as handle:
        for command in commands:
            handle.write(f"$ {_command_text(command)}\n")
            handle.flush()
            result = subprocess.run(
                list(map(str, command)),
                stdout=handle,
                stderr=subprocess.STDOUT,
                env=headline_env,
                check=False,
            )
            if result.returncode:
                _state(root, step, "failed", f"exit={result.returncode}")
                return False
    paths = list(evidence())
    write_attested_json(
        receipt,
        {
            "schema_version": 1,
            "step": step,
            "status": "complete",
            "duration_s": time.time() - started,
            "headline_env_sanitized": True,
            "commands": [list(map(str, command)) for command in commands],
        },
        evidence=[log, *paths],
    )
    _state(root, step, "complete")
    return True


def _success_run_dirs(root: Path) -> list[Path]:
    output = []
    if not root.is_dir():
        return output
    for path in sorted(item for item in root.iterdir() if item.is_dir()):
        try:
            exit_info = json.loads((path / "exit.json").read_text(encoding="utf-8"))
        except (OSError, ValueError, TypeError, json.JSONDecodeError):
            continue
        if (
            exit_info.get("status") == "complete_valid"
            and exit_info.get("exit_code") == 0
            and (path / "hashes.json").is_file()
        ):
            output.append(path)
    return output


def _hash_ledgers(root: Path) -> list[Path]:
    return [path / "hashes.json" for path in _success_run_dirs(root)]


def _archive_partial(path: Path, recovery_root: Path) -> None:
    if not path.exists() and not path.is_symlink():
        return
    recovery_root.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    destination = recovery_root / f"{stamp}-{path.name}-{os.getpid()}"
    os.replace(path, destination)


def _combined_view(static_root: Path, candidate_root: Path, target: Path) -> None:
    if target.is_dir():
        return
    temporary = target.with_name(f".{target.name}.{os.getpid()}.tmp")
    if temporary.exists():
        _archive_partial(temporary, target.parent / "recovery")
    temporary.mkdir(parents=True)
    runs = [("static", path) for path in _success_run_dirs(static_root)]
    runs += [("candidate", path) for path in _success_run_dirs(candidate_root)]
    if len(runs) != 2:
        raise QueueError(
            "combined calibration view requires exactly one successful Static "
            "and one successful candidate run"
        )
    for label, source in runs:
        (temporary / f"{label}--{source.name}").symlink_to(source.resolve())
    os.replace(temporary, target)


def _read_table(path: Path):
    import pyarrow.parquet as pq

    return pq.read_table(path).to_pandas()


def _nonfinite_updates(run_root: Path) -> int:
    def is_missing(value: object) -> bool:
        if value is None:
            return True
        return isinstance(value, float) and math.isnan(value)

    count = 0
    for run in _success_run_dirs(run_root):
        path = run / "updates.parquet"
        if not path.is_file():
            continue
        frame = _read_table(path)
        for row in frame.to_dict("records"):
            raw_reason = row.get("failure_reason")
            reason = "" if is_missing(raw_reason) else str(raw_reason)
            bad_value = False
            for name in ("grad_norm", "candidate_delta_norm"):
                value = row.get(name)
                # A terminated request may legitimately have no candidate
                # metrics.  Missing parquet scalars arrive as float NaN; they
                # are absence, not evidence of a non-finite GPU update.
                if (
                    not is_missing(value)
                    and isinstance(value, (int, float))
                    and not math.isfinite(float(value))
                ):
                    bad_value = True
            if NONFINITE.search(reason) or bad_value:
                count += 1
    return count


def _runtime_safety_counts(run_root: Path) -> dict[str, int]:
    version_mismatch = 0
    fallback = 0
    canary_failures = 0
    for run in _success_run_dirs(run_root):
        summary_path = run / "request_summary.parquet"
        if summary_path.is_file():
            frame = _read_table(summary_path)
            if "version_mismatch_count" in frame:
                version_mismatch += int(frame["version_mismatch_count"].fillna(0).sum())
            if "adaptation_fallback_count" in frame:
                fallback += int(frame["adaptation_fallback_count"].fillna(0).sum())
        rounds_path = run / "rounds.parquet"
        if rounds_path.is_file():
            frame = _read_table(rounds_path)
            if "version_canary_ok" in frame:
                canary_failures += int((frame["version_canary_ok"] == False).sum())  # noqa: E712
    return {
        "version_mismatch_count": version_mismatch,
        "adaptation_fallback_count": fallback,
        "version_canary_failures": canary_failures,
        "nonfinite_update_count": _nonfinite_updates(run_root),
    }


def summarize_analysis(
    analysis_root: Path,
    run_root: Path,
    gate: dict[str, Any],
    *,
    expected_contexts: Sequence[int] | None = None,
    expected_concurrencies: Sequence[int] | None = None,
    expected_mode: str | None = None,
) -> dict[str, Any]:
    table_path = analysis_root / "p5_long_context_acceptance.parquet"
    claims_path = analysis_root / "p5_claim_gates.json"
    if not table_path.is_file() or not claims_path.is_file():
        raise QueueError(f"analysis is incomplete: {analysis_root}")
    frame = _read_table(table_path)
    if "method" not in frame or not (frame["method"] == "tts").any():
        raise QueueError("analysis contains no TTS rows")
    tts = frame[frame["method"] == "tts"].copy()
    if expected_mode is not None and "weight_update_mode" in frame:
        tts_modes = set(tts["weight_update_mode"].dropna().astype(str))
        static_modes = set(
            frame.loc[frame["method"] == "static", "weight_update_mode"]
            .dropna()
            .astype(str)
        )
        if tts_modes != {expected_mode} or static_modes != {expected_mode}:
            raise QueueError(
                "analysis mode pairing drift: "
                f"Static={sorted(static_modes)}, TTS={sorted(tts_modes)}, "
                f"expected={expected_mode}"
            )
    gain_column = (
        "acceptance_gain_vs_static"
        if "acceptance_gain_vs_static" in tts
        else "acceptance_gain_vs_baseline"
    )
    required = {
        gain_column,
        "context_length",
        "offered_concurrency",
        "lcag",
        "lcag_ci_low",
        "throughput_speedup_vs_static",
        "peak_hbm_bytes",
        "version_mismatch_count",
        "exactness_violations",
    }
    missing = sorted(required - set(tts.columns))
    if missing:
        raise QueueError(f"analysis lacks required columns: {missing}")
    contexts = sorted({int(value) for value in tts["context_length"]})
    concurrencies = sorted({int(value) for value in tts["offered_concurrency"]})
    expected_contexts = tuple(int(v) for v in (expected_contexts or contexts))
    expected_concurrencies = tuple(
        int(v) for v in (expected_concurrencies or concurrencies)
    )
    missing_cells = []
    loads = {}
    for concurrency in expected_concurrencies:
        group = tts[tts["offered_concurrency"] == concurrency]
        by_context = {
            int(row.context_length): float(getattr(row, gain_column))
            for row in group.itertuples()
        }
        absent = sorted(set(expected_contexts) - set(by_context))
        missing_cells.extend((concurrency, context) for context in absent)
        lcag = float(group["lcag"].dropna().iloc[0]) if len(group) else float("nan")
        lcag_ci_low = (
            float(group["lcag_ci_low"].dropna().iloc[0])
            if len(group) and not group["lcag_ci_low"].dropna().empty
            else float("nan")
        )
        loads[str(concurrency)] = {
            "acceptance_gain_by_context": by_context,
            "lcag": lcag,
            "lcag_ci_low": lcag_ci_low,
            "positive_contexts": sum(value > 0 for value in by_context.values()),
            "worst_context_gain": min(by_context.values(), default=float("nan")),
            "min_throughput_ratio": float(
                group["throughput_speedup_vs_static"].min()
            )
            if len(group)
            else float("nan"),
            "peak_hbm_bytes": int(group["peak_hbm_bytes"].max())
            if len(group)
            else 0,
            "max_hbm_delta_bytes": 0,
        }
    static = frame[frame["method"] == "static"]
    for concurrency, values in loads.items():
        current = tts[tts["offered_concurrency"] == int(concurrency)]
        baseline = static[static["offered_concurrency"] == int(concurrency)]
        baseline_hbm = {
            int(row.context_length): int(row.peak_hbm_bytes)
            for row in baseline.itertuples()
        }
        deltas = [
            int(row.peak_hbm_bytes) - baseline_hbm.get(int(row.context_length), 0)
            for row in current.itertuples()
            if int(row.context_length) in baseline_hbm
        ]
        values["max_hbm_delta_bytes"] = max(deltas, default=0)
    runtime = _runtime_safety_counts(run_root)
    exactness = int(tts["exactness_violations"].fillna(0).sum())
    analysis_version_mismatch = int(
        tts["version_mismatch_count"].fillna(0).sum()
    )
    peak_hbm = max((row["peak_hbm_bytes"] for row in loads.values()), default=0)
    hbm_delta = max(
        (row["max_hbm_delta_bytes"] for row in loads.values()), default=0
    )
    hard_safety = {
        "nonfinite_updates_zero": runtime["nonfinite_update_count"] == 0,
        "version_mismatch_zero": (
            runtime["version_mismatch_count"] == 0
            and runtime["version_canary_failures"] == 0
            and analysis_version_mismatch == 0
        ),
        "exactness_violations_zero": exactness == 0,
        "fallback_zero": runtime["adaptation_fallback_count"] == 0,
        "peak_hbm_within_limit": peak_hbm
        <= float(gate["max_peak_hbm_gib"]) * GIB,
        "hbm_delta_within_limit": hbm_delta
        <= float(gate["max_hbm_delta_gib"]) * GIB,
    }
    claims = json.loads(claims_path.read_text(encoding="utf-8"))
    claim_rows = [row for row in claims if row.get("method") == "tts"]
    return {
        "contexts": contexts,
        "concurrencies": concurrencies,
        "missing_cells": missing_cells,
        "loads": loads,
        "hard_safety": hard_safety,
        "hard_safety_pass": all(hard_safety.values()),
        "engineering_pass": all(
            row["min_throughput_ratio"] >= float(gate["min_throughput_ratio"])
            for row in loads.values()
        ),
        "runtime_counts": runtime,
        "analysis_exactness_violations": exactness,
        "analysis_version_mismatch_count": analysis_version_mismatch,
        "canonical_algorithmic_passes": sum(
            row.get("algorithmic_pass") is True for row in claim_rows
        ),
        "canonical_engineering_passes": sum(
            row.get("engineering_pass") is True for row in claim_rows
        ),
    }


def calibration_verdict(summary: dict[str, Any], gate: dict[str, Any]) -> dict:
    loads = list(summary["loads"].values())
    algorithmic = bool(loads) and all(
        math.isfinite(row["lcag"])
        and math.isfinite(row["lcag_ci_low"])
        and row["lcag"] > float(gate["min_lcag"])
        and row["positive_contexts"] >= int(gate["min_positive_contexts"])
        and row["worst_context_gain"] >= -float(gate["max_context_regression"])
        for row in loads
    )
    return {
        "algorithmic_screen_pass": algorithmic,
        "engineering_screen_pass": summary["engineering_pass"],
        "hard_safety_pass": summary["hard_safety_pass"],
        "eligible": algorithmic and summary["hard_safety_pass"],
    }


def heldout_verdict(summary: dict[str, Any], gate: dict[str, Any]) -> dict:
    expected_contexts = {int(v) for v in gate["expected_contexts"]}
    load_verdicts = {}
    for concurrency in (int(v) for v in gate["expected_concurrencies"]):
        row = summary["loads"].get(str(concurrency), {})
        gains = {
            int(key): float(value)
            for key, value in row.get("acceptance_gain_by_context", {}).items()
        }
        all_contexts = set(gains) == expected_contexts
        nonnegative = all(
            value >= -float(gate["max_context_regression"])
            for value in gains.values()
        )
        lcag = row.get("lcag", float("nan"))
        lcag_ci_low = row.get("lcag_ci_low", float("nan"))
        lcag_pass = math.isfinite(lcag) and lcag > float(gate["min_lcag"])
        # Strict inequality is intentional: a BCa lower bound exactly at zero
        # does not establish TTS > Static on the paired long-context aggregate.
        lcag_ci_pass = math.isfinite(lcag_ci_low) and lcag_ci_low > float(
            gate["min_lcag_ci_low"]
        )
        positives = row.get("positive_contexts", 0) >= int(
            gate["min_positive_contexts_per_concurrency"]
        )
        load_verdicts[str(concurrency)] = {
            "all_contexts_present": all_contexts,
            "all_context_point_estimates_nonnegative": nonnegative,
            "long_context_lcag_positive": lcag_pass,
            "long_context_lcag_ci_low_positive": lcag_ci_pass,
            "positive_context_count_pass": positives,
            "algorithmic_pass": (
                all_contexts and nonnegative and lcag_pass and lcag_ci_pass and positives
            ),
            "engineering_pass": row.get("min_throughput_ratio", 0.0)
            >= float(gate["min_throughput_ratio"]),
        }
    algorithmic = bool(load_verdicts) and all(
        row["algorithmic_pass"] for row in load_verdicts.values()
    )
    engineering = bool(load_verdicts) and all(
        row["engineering_pass"] for row in load_verdicts.values()
    )
    ready = algorithmic and summary["hard_safety_pass"]
    return {
        "load_verdicts": load_verdicts,
        "algorithmic_pass": algorithmic,
        "engineering_pass": engineering,
        "hard_safety_pass": summary["hard_safety_pass"],
        "downstream_ready": ready,
        "interpretation": (
            "engineering_pass is reported independently; downstream_ready "
            "establishes acceptance plus exactness/version/HBM safety only"
        ),
    }


def choose_winner(rows: list[dict[str, Any]]) -> dict[str, Any] | None:
    eligible = [row for row in rows if row["verdict"]["eligible"]]
    if not eligible:
        return None

    def score(row):
        loads = list(row["summary"]["loads"].values())
        return (
            min(value["lcag_ci_low"] for value in loads),
            sum(value["lcag"] for value in loads) / len(loads),
            int(row["summary"]["engineering_pass"]),
            min(value["min_throughput_ratio"] for value in loads),
            -max(value["max_hbm_delta_bytes"] for value in loads),
            row["candidate"]["candidate_id"],
        )

    return max(eligible, key=score)


def _common_run_args(args, manifest: Path, artifact_root: Path) -> list[str]:
    return [
        str(args.lightcone_cli),
        "run-manifest",
        "--manifest",
        str(manifest),
        "--artifact-root",
        str(artifact_root),
        "--lockfile",
        str(args.lockfile),
        "--runtime-root",
        str(args.runtime_root),
        "--model-roots",
        str(args.model_roots),
    ]


def _validation_args(
    args,
    manifest: Path,
    artifact_root: Path,
    coverage: Path,
    methods: Sequence[str],
    candidate: Candidate | None = None,
) -> list[str]:
    command = [
        str(args.lightcone_cli),
        "validate-artifacts",
        "--artifact-root",
        str(artifact_root),
        "--manifest",
        str(manifest),
        "--methods",
        *methods,
        "--coverage-output",
        str(coverage),
    ]
    if candidate:
        command += [
            "--weight-update-mode",
            candidate.weight_update_mode,
            "--learning-rate",
            repr(candidate.learning_rate),
        ]
    return command


def _analysis_args(
    args,
    manifest: Path,
    artifact_root: Path,
    analysis_root: Path,
    candidate: Candidate,
) -> list[str]:
    return [
        str(args.lightcone_cli),
        "analyze",
        "--artifact-root",
        str(artifact_root),
        "--output-dir",
        str(analysis_root),
        "--manifest",
        str(manifest),
        "--methods",
        "static",
        "tts",
        "--weight-update-mode",
        candidate.weight_update_mode,
        "--learning-rate",
        repr(candidate.learning_rate),
        "--baseline",
        "static",
    ]


def build_plan(args, candidates: Sequence[Candidate]) -> dict[str, Any]:
    root = args.artifact_root
    static_root = root / "calibration" / "static"
    entries = [
        {
            "step": "calibration-static",
            "command": _common_run_args(args, args.calibration_manifest, static_root)
            + ["--methods", "static"],
        }
    ]
    for candidate in candidates:
        candidate_root = root / "calibration" / "candidates" / candidate.candidate_id
        entries.append(
            {
                "step": f"calibration-{candidate.candidate_id}",
                "command": _common_run_args(
                    args, args.calibration_manifest, candidate_root / "runs"
                )
                + [
                    "--methods",
                    "tts",
                    "--weight-update-mode",
                    candidate.weight_update_mode,
                    "--learning-rate",
                    repr(candidate.learning_rate),
                ],
            }
        )
    return {
        "schema_version": 1,
        "ordering": [
            "one shared Static calibration",
            "isolated TTS candidates",
            "frozen held-out Static/TTS evaluation",
            "DOWNSTREAM_READY permits L0 then trace/controller then L1/L2/L3",
        ],
        "steps": entries,
    }


def _contract(args) -> dict[str, Any]:
    repository = Path(__file__).resolve().parents[2]
    paths = [
        args.calibration_manifest,
        args.evaluation_manifest,
        args.candidate_spec,
        args.lockfile,
        args.model_roots,
        Path(__file__).resolve(),
    ]
    return {
        "schema_version": 1,
        "inputs": [
            {"path": str(path.resolve()), "sha256": sha256_file(path)}
            for path in paths
        ],
        "runtime_root": str(args.runtime_root.resolve()),
        "lightcone_cli": str(args.lightcone_cli),
        "runtime_source_trees": {
            "lightcone_spec": source_tree_fingerprint(
                repository / "src/lightcone_spec"
            ),
            "sglang_srt": source_tree_fingerprint(
                repository / "sglang/python/sglang/srt"
            ),
        },
    }


def _ensure_contract(args) -> Path:
    path = args.artifact_root / "queue-contract.json"
    expected = _contract(args)
    if path.is_file() or Path(str(path) + ".sha256").is_file():
        actual = load_attested_json(path)
        comparable = {key: value for key, value in actual.items() if key != "evidence"}
        if comparable != expected:
            raise QueueError(
                "queue contract changed; use a new artifact root rather than "
                "mixing calibration epochs"
            )
    else:
        write_attested_json(path, expected, evidence=[])
    return path


def _analysis_evidence(analysis_root: Path, *run_roots: Path) -> list[Path]:
    evidence = [
        analysis_root / "analysis-hashes.json",
        analysis_root / "p5_claim_gates.json",
        analysis_root / "p5_long_context_acceptance.parquet",
    ]
    for root in run_roots:
        evidence.extend(_hash_ledgers(root))
    return evidence


def run_queue(args) -> int:
    args.artifact_root.mkdir(parents=True, exist_ok=True)
    lock_path = args.artifact_root / ".queue.lock"
    with lock_path.open("a+", encoding="utf-8") as lock:
        try:
            fcntl.flock(lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise QueueError(f"another calibration queue owns {lock_path}") from exc

        candidates, calibration_gate, evaluation_gate = load_candidate_spec(
            args.candidate_spec
        )
        _manifest_contract(args.calibration_manifest, args.evaluation_manifest)
        contract_path = _ensure_contract(args)
        _state(args.artifact_root, "queue", "started")

        static_root = args.artifact_root / "calibration" / "static"
        static_coverage = static_root / "coverage.json"
        static_commands = [
            _common_run_args(args, args.calibration_manifest, static_root)
            + ["--methods", "static"],
            _validation_args(
                args,
                args.calibration_manifest,
                static_root,
                static_coverage,
                ["static"],
            ),
        ]
        if not _run_commands(
            args.artifact_root,
            "calibration-static",
            static_commands,
            static_root / "complete.json",
            lambda: [static_coverage, Path(str(static_coverage) + ".sha256"), *_hash_ledgers(static_root)],
        ):
            raise QueueError("Static calibration failed; no candidate is comparable")

        candidate_rows = []
        for candidate in candidates:
            candidate_root = (
                args.artifact_root
                / "calibration"
                / "candidates"
                / candidate.candidate_id
            )
            runs = candidate_root / "runs"
            coverage = candidate_root / "coverage.json"
            run_commands = [
                _common_run_args(args, args.calibration_manifest, runs)
                + [
                    "--methods",
                    "tts",
                    "--weight-update-mode",
                    candidate.weight_update_mode,
                    "--learning-rate",
                    repr(candidate.learning_rate),
                ],
                _validation_args(
                    args,
                    args.calibration_manifest,
                    runs,
                    coverage,
                    ["tts"],
                    candidate,
                ),
            ]
            run_ok = _run_commands(
                args.artifact_root,
                f"calibration-{candidate.candidate_id}",
                run_commands,
                candidate_root / "run-complete.json",
                lambda runs=runs, coverage=coverage: [
                    coverage,
                    Path(str(coverage) + ".sha256"),
                    *_hash_ledgers(runs),
                ],
            )
            if not run_ok:
                candidate_rows.append(
                    {
                        "candidate": candidate.to_dict(),
                        "status": "run_failed",
                        "verdict": {"eligible": False},
                    }
                )
                continue
            combined = candidate_root / "combined"
            _combined_view(static_root, runs, combined)
            analysis = candidate_root / "analysis"
            analysis_receipt = candidate_root / "analysis-complete.json"
            if analysis.is_dir() and not analysis_receipt.is_file():
                _archive_partial(analysis, candidate_root / "recovery")
            analysis_command = _analysis_args(
                args,
                args.calibration_manifest,
                combined,
                analysis,
                candidate,
            )
            analysis_ok = _run_commands(
                args.artifact_root,
                f"analysis-{candidate.candidate_id}",
                [analysis_command],
                analysis_receipt,
                lambda analysis=analysis, runs=runs: _analysis_evidence(
                    analysis, static_root, runs
                ),
            )
            if not analysis_ok:
                candidate_rows.append(
                    {
                        "candidate": candidate.to_dict(),
                        "status": "analysis_failed",
                        "verdict": {"eligible": False},
                    }
                )
                continue
            summary = summarize_analysis(
                analysis,
                runs,
                calibration_gate,
                expected_mode=candidate.weight_update_mode,
            )
            candidate_rows.append(
                {
                    "candidate": candidate.to_dict(),
                    "status": "measured",
                    "summary": summary,
                    "verdict": calibration_verdict(summary, calibration_gate),
                }
            )

        selection_path = args.artifact_root / "calibration-selection.json"
        if selection_path.is_file() or Path(str(selection_path) + ".sha256").is_file():
            selection = load_attested_json(selection_path)
            winner_payload = selection.get("winner")
        else:
            winner = choose_winner(candidate_rows)
            winner_payload = winner["candidate"] if winner else None
            selection = write_attested_json(
                selection_path,
                {
                    "schema_version": 1,
                    "status": "winner_selected" if winner else "scientifically_blocked",
                    "selection_dataset": "math500",
                    "heldout_dataset": "livecodebench",
                    "calibration_gate": calibration_gate,
                    "candidates": candidate_rows,
                    "winner": winner_payload,
                    "selection_rule": (
                        "hard safety and positive long-context screen; rank by "
                        "paired LCAG CI, LCAG, then independent engineering cost"
                    ),
                },
                evidence=[
                    contract_path,
                    *(
                        path
                        for candidate in candidates
                        for path in _analysis_evidence(
                            args.artifact_root
                            / "calibration"
                            / "candidates"
                            / candidate.candidate_id
                            / "analysis",
                            static_root,
                            args.artifact_root
                            / "calibration"
                            / "candidates"
                            / candidate.candidate_id
                            / "runs",
                        )
                        if path.is_file()
                    ),
                ],
            )
        if not winner_payload:
            _state(args.artifact_root, "queue", "scientifically_blocked", "no safe positive TTS candidate")
            raise ScientificBlock("no calibrated TTS candidate passed the screen")
        winner = Candidate(
            winner_payload["candidate_id"],
            winner_payload["weight_update_mode"],
            float(winner_payload["learning_rate"]),
        )

        heldout_root = args.artifact_root / "heldout" / "runs"
        heldout_coverage = args.artifact_root / "heldout" / "coverage.json"
        heldout_commands = [
            _common_run_args(
                args, args.evaluation_manifest, heldout_root
            )
            + [
                "--methods",
                "static",
                "tts",
                "--weight-update-mode",
                winner.weight_update_mode,
                "--learning-rate",
                repr(winner.learning_rate),
            ],
            _validation_args(
                args,
                args.evaluation_manifest,
                heldout_root,
                heldout_coverage,
                ["static", "tts"],
                winner,
            ),
        ]
        if not _run_commands(
            args.artifact_root,
            "heldout-static-tts",
            heldout_commands,
            args.artifact_root / "heldout" / "run-complete.json",
            lambda: [
                heldout_coverage,
                Path(str(heldout_coverage) + ".sha256"),
                *_hash_ledgers(heldout_root),
            ],
        ):
            raise QueueError("frozen held-out Static/TTS run failed")

        heldout_analysis = args.artifact_root / "heldout" / "analysis"
        heldout_analysis_receipt = (
            args.artifact_root / "heldout" / "analysis-complete.json"
        )
        if heldout_analysis.is_dir() and not heldout_analysis_receipt.is_file():
            _archive_partial(
                heldout_analysis, args.artifact_root / "heldout" / "recovery"
            )
        if not _run_commands(
            args.artifact_root,
            "heldout-analysis",
            [
                _analysis_args(
                    args,
                    args.evaluation_manifest,
                    heldout_root,
                    heldout_analysis,
                    winner,
                )
            ],
            heldout_analysis_receipt,
            lambda: _analysis_evidence(heldout_analysis, heldout_root),
        ):
            raise QueueError("frozen held-out analysis failed")

        summary = summarize_analysis(
            heldout_analysis,
            heldout_root,
            evaluation_gate,
            expected_contexts=evaluation_gate["expected_contexts"],
            expected_concurrencies=evaluation_gate["expected_concurrencies"],
            expected_mode=winner.weight_update_mode,
        )
        verdict = heldout_verdict(summary, evaluation_gate)
        gate_path = args.artifact_root / "heldout-gate.json"
        if gate_path.is_file() or Path(str(gate_path) + ".sha256").is_file():
            gate_payload = load_attested_json(gate_path)
        else:
            gate_payload = write_attested_json(
                gate_path,
                {
                    "schema_version": 1,
                    "winner": winner.to_dict(),
                    "calibration_selection_sha256": sha256_file(selection_path),
                    "evaluation_gate": evaluation_gate,
                    "summary": summary,
                    "verdict": verdict,
                },
                evidence=[
                    selection_path,
                    *_analysis_evidence(heldout_analysis, heldout_root),
                ],
            )
        verdict = gate_payload["verdict"]
        if not verdict["downstream_ready"]:
            _state(
                args.artifact_root,
                "queue",
                "scientifically_blocked",
                "held-out TTS acceptance gate failed",
            )
            raise ScientificBlock(
                "held-out TTS did not establish nonnegative 512--40K buckets "
                "and positive paired 4K--40K LCAG CI for every load"
            )
        ready_path = args.artifact_root / "DOWNSTREAM_READY.json"
        if ready_path.is_file() or Path(str(ready_path) + ".sha256").is_file():
            load_attested_json(ready_path)
        else:
            write_attested_json(
                ready_path,
                {
                    "schema_version": 1,
                    "status": "ready",
                    "winner": winner.to_dict(),
                    "heldout_gate_sha256": sha256_file(gate_path),
                    "permitted_next_stages": [
                        "L0 held-out evaluation",
                        "paired trace",
                        "L1/L2 learned-policy gates",
                        "L3 held-out transport gate",
                    ],
                    "engineering_pass": gate_payload["verdict"][
                        "engineering_pass"
                    ],
                },
                evidence=[gate_path, selection_path],
            )
        _state(args.artifact_root, "queue", "complete", str(ready_path))
        print(json.dumps(load_attested_json(ready_path), indent=2, sort_keys=True))
        return 0


def parser() -> argparse.ArgumentParser:
    repository = Path(__file__).resolve().parents[2]
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument("--artifact-root", type=Path, required=True)
    result.add_argument(
        "--calibration-manifest",
        type=Path,
        default=repository
        / "manifests/p5/p5_priority_dflash_calibration_v1.json",
    )
    result.add_argument(
        "--evaluation-manifest",
        type=Path,
        default=repository
        / "manifests/p5/p5_priority_dflash_0_40k_v1.json",
    )
    result.add_argument(
        "--candidate-spec",
        type=Path,
        default=Path(__file__).with_name("priority_calibration_candidates_v1.json"),
    )
    result.add_argument("--lockfile", type=Path, required=True)
    result.add_argument("--model-roots", type=Path, required=True)
    result.add_argument("--runtime-root", type=Path, required=True)
    result.add_argument("--lightcone-cli", default="lightcone-spec")
    result.add_argument(
        "--print-plan",
        action="store_true",
        help="print the immutable calibration commands without running them",
    )
    return result


def main(argv: Sequence[str] | None = None) -> int:
    args = parser().parse_args(argv)
    for name in (
        "artifact_root",
        "calibration_manifest",
        "evaluation_manifest",
        "candidate_spec",
        "lockfile",
        "model_roots",
        "runtime_root",
    ):
        setattr(args, name, getattr(args, name).expanduser().resolve())
    try:
        candidates, _, _ = load_candidate_spec(args.candidate_spec)
        _manifest_contract(args.calibration_manifest, args.evaluation_manifest)
        for path in (args.lockfile, args.model_roots):
            if not path.is_file():
                raise QueueError(f"required input is missing: {path}")
        if args.print_plan:
            print(json.dumps(build_plan(args, candidates), indent=2, sort_keys=True))
            return 0
        return run_queue(args)
    except ScientificBlock as exc:
        print(f"scientifically blocked: {exc}", file=sys.stderr)
        return 3
    except (QueueError, OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"calibration queue failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
